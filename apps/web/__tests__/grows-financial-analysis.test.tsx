import { cleanup, fireEvent, render, screen, within } from '@testing-library/react';
import { afterEach, expect, it } from 'vitest';
import FinancialAnalysis from '@/components/grows/FinancialAnalysis';
import { createScenarios } from '@/lib/obras/simulation';
import { financialContext, projectFinancials } from '@/lib/obras/financial-projection';
afterEach(cleanup);
it('integra historial y un único objetivo en el general, sin escenarios ni edición de supuestos',()=>{
  const obra=createScenarios()[1];
  const context=financialContext(obra);
  const target=projectFinancials(obra,context.defaults);
  const value=new Intl.NumberFormat('es-AR',{style:'currency',currency:'USD',currencyDisplay:'code'}).format(target.terminalMcuCents/100).replace(/\u00a0/g, ' ');
  render(<FinancialAnalysis obra={obra} position={{quantity:3333,totalCents:349965}}/>);
  const general=screen.getByRole('region',{name:'General de MCU'});
  expect(within(general).getByRole('heading',{name:'Valor objetivo por MCU'})).toBeTruthy();
  expect(within(general).getByRole('heading',{name:'Valor de referencia por MCU'})).toBeTruthy();
  expect(within(general).getAllByRole('img')).toHaveLength(1);
  expect(screen.getAllByTestId('target-projection')).toHaveLength(1);
  expect(within(general).getByText(value)).toBeTruthy();
  expect(screen.queryByText('Probá tu hipótesis')).toBeNull();
  expect(screen.queryByRole('spinbutton')).toBeNull();
  expect(screen.queryByRole('button',{name:/Adverso|Favorable/})).toBeNull();
  fireEvent.click(screen.getByRole('button',{name:'3M'}));
  expect(within(general).getByText(value)).toBeTruthy();
  expect(screen.getByText('Tu participación al valor objetivo')).toBeTruthy();
  expect(screen.getByText('Cómo se calcula el valor objetivo')).toBeTruthy();
  expect(screen.getByText('Comparables de Santa Fe')).toBeTruthy();
});
